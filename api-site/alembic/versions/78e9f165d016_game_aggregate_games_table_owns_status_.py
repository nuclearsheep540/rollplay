"""game aggregate: games table owns status and play state

Revision ID: 78e9f165d016
Revises: b1ae5a5e538b
Create Date: 2026-09-06 19:28:38.064218

The session was carrying the game's status and the game's state. Only two
commands ever wrote those columns — start and the take-down — and both are
operations on a game. This moves them onto a `games` table, one row per play,
whose id IS the api-game room id.

Schema changes are autogenerated; the precondition and the data step around them
are hand-authored, and their ORDER matters:

1. REFUSE if any session is not 'inactive'. A live session's MongoDB room is
   keyed by the SESSION id, which no game row will ever match — so a running
   game cannot survive this migration. End every game before deploying.

2. Create `games`, and add `sessions.next_game_name` (empty: nothing was planned
   under the old model).

3. BEFORE the drops, because it reads the columns being dropped: give every
   session that was ever PLAYED one ENDED game carrying its state and its real
   timestamps. This is what keeps continuity alive across the deploy — without
   it the first Start after this migration seeds from nothing and strands the
   players' token positions, which is exactly the bug the one-session model was
   introduced to fix.

   "Played" means it has a started_at or any non-default state. A session that
   was created and never used gets no game: inventing one would put a night in
   the history that never happened.

4. Drop the twelve columns from `sessions`.

Downgrade restores the columns and copies each session's newest ended game's
state and timestamps back onto it, then drops `games`. It can only restore the
NEWEST game per session — older history has no representation on the old shape.
"""

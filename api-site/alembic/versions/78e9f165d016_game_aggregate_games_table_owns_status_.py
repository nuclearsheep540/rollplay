# The state columns, in the order both the carry-forward and the restore use them.
# Split by type because psycopg2 cannot adapt a bare Python dict: the JSONB ones
# must be bound with an explicit type or the INSERT fails on the first row that
# actually holds state — which is every row this step exists for.
JSONB_STATE_COLUMNS = (
    'map_token_seed',
    'map_token_state',
    'adventure_log',
    'map_config',
    'image_config',
    'audio_config',
    'spotify_config',
)
STATE_COLUMNS = JSONB_STATE_COLUMNS + ('active_display',)


def _refuse_while_anything_is_running(connection) -> None:
    """Step 1 — a live session cannot cross this migration.

    Its hot room in api-game is keyed by the session id, and after this every
    room is keyed by a game id. There is no mapping that could rescue it, so the
    migration refuses rather than silently orphaning a game people are playing.
    """
    running = connection.execute(
        sa.text("SELECT count(*) FROM sessions WHERE status <> 'inactive'")
    ).scalar_one()
    if running:
        raise RuntimeError(
            f"End every running game before migrating: {running} session(s) are not inactive. "
            f"End them from the campaign drawer on the code being replaced "
            f"(or `admin.py pause-all --yes` there), then deploy."
        )


def _carry_played_sessions_into_games(connection) -> None:
    """Step 3 — every session that was played becomes its own first ENDED game.

    Runs BEFORE the column drops because it reads them.
    """
    played = connection.execute(sa.text(f"""
        SELECT id, campaign_id, host_id, created_at, started_at, stopped_at,
               {', '.join(STATE_COLUMNS)}
        FROM sessions
        WHERE started_at IS NOT NULL
           OR map_token_state <> '{{}}'::jsonb
           OR map_token_seed  <> '{{}}'::jsonb
           OR adventure_log   <> '[]'::jsonb
           OR map_config      <> '{{}}'::jsonb
           OR image_config    <> '{{}}'::jsonb
           OR audio_config    <> '{{}}'::jsonb
           OR spotify_config  <> '{{}}'::jsonb
           OR active_display IS NOT NULL
    """)).fetchall()

    insert_game = sa.text(f"""
        INSERT INTO games (
            id, session_id, campaign_id, host_id, status,
            name, created_at, started_at, ended_at, ended_by,
            urls_expire_at, summary, attendance,
            {', '.join(STATE_COLUMNS)}
        ) VALUES (
            :game_id, :session_id, :campaign_id, :host_id, 'ended',
            NULL, :created_at, :started_at, :ended_at, NULL,
            NULL, NULL, '[]',
            {', '.join(':' + column for column in STATE_COLUMNS)}
        )
    """).bindparams(*(
        sa.bindparam(column, type_=postgresql.JSONB) for column in JSONB_STATE_COLUMNS
    ))

    for row in played:
        session = row._mapping
        connection.execute(
            insert_game,
            {
                # Minted in Python, matching the previous migration: the ids
                # are few and this keeps the step readable next to its bindings.
                "game_id": uuid.uuid4(),
                "session_id": session["id"],
                "campaign_id": session["campaign_id"],
                "host_id": session["host_id"],
                # A row with state but no timestamps was still a game that
                # happened; the session's own creation time keeps the
                # "newest ended" ordering defined rather than null.
                "created_at": session["started_at"] or session["created_at"],
                "started_at": session["started_at"],
                "ended_at": session["stopped_at"] or session["started_at"] or session["created_at"],
                **{column: session[column] for column in STATE_COLUMNS},
            },
        )

    print(f"game migration: created {len(played)} ended game(s) from played sessions")


def _restore_newest_game_onto_sessions(connection) -> None:
    """Downgrade helper — put the last game's state back on its session."""
    restored = connection.execute(sa.text(f"""
        UPDATE sessions AS s
        SET started_at = g.started_at,
            stopped_at = g.ended_at,
            {', '.join(f'{column} = g.{column}' for column in STATE_COLUMNS)}
        FROM (
            SELECT DISTINCT ON (session_id) *
            FROM games
            WHERE status = 'ended'
            ORDER BY session_id, ended_at DESC NULLS LAST, created_at DESC
        ) AS g
        WHERE g.session_id = s.id
    """)).rowcount
    print(f"game migration downgrade: restored {restored} session(s) from their newest game")


